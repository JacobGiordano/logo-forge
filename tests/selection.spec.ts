// tests/fixtures/test-logo.png (32x32) is too small to trigger the
// selection view at all — SELECT_SKIP_MAX_DIM (js/app.js) is 256px, and an
// image at or below that in both dimensions skips straight to the
// immediate-trace-ready flow. tests/fixtures/select-sheet.png (new, 512x512)
